import assert from 'node:assert/strict';
import {adaptiveDailyLimit,formatTime,localDate,mastery,normalizeAnswer,recordAttempt,resultSummary,scheduleCard,shiftDate,speechSimilarity} from './learning-core.mjs';
assert.equal(normalizeAnswer('  Être  d’accord '),"etre d'accord");
assert.equal(shiftDate('2026-12-31',1),'2027-01-01');
assert.match(localDate(new Date()),/^\d{4}-\d{2}-\d{2}$/);
assert.deepEqual([0,10,20,30].map(adaptiveDailyLimit),[20,15,10,5]);
let performance=recordAttempt({},true,'2026-09-01');performance=recordAttempt(performance,true,'2026-09-02');performance=recordAttempt(performance,true,'2026-09-03');
let card=scheduleCard({},'known','2026-09-01');card=scheduleCard(card,'known','2026-09-02');assert.equal(mastery(performance,card),true);
const items=[{id:1,word:'one',translation:'un'},{id:2,word:'two',translation:'deux'}];assert.deepEqual(resultSummary([{...items[0],ok:true}],items),{total:2,correct:1,score:50,missed:[{...items[1],ok:false}]});
assert.equal(formatTime(65), '1:05');
assert.equal(speechSimilarity("from my perspective", "from my perspective"), 100);
assert.ok(speechSimilarity("from my perspective", "from perspective") >= 60);
